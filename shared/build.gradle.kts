// The balldontlie API key comes from `local.properties` (`nba.api.key=...`), then from the
// `NBA_API_KEY` environment variable, then from the `nba-api.properties` file in the repository.
val nbaApiKey: String = run {
    fun readKey(fileName: String): String? {
        val file = rootProject.file(fileName)
        if (!file.exists()) return null
        val properties = Properties()
        file.inputStream().use(properties::load)
        return properties.getProperty("nba.api.key")?.takeIf { it.isNotBlank() }
    }
    readKey("local.properties")
        ?: providers.environmentVariable("NBA_API_KEY").orNull?.takeIf { it.isNotBlank() }
        ?: readKey("nba-api.properties")
        ?: ""
}

val generateApiConfig by tasks.registering {
    val apiKey = nbaApiKey
    val outputDir = layout.buildDirectory.dir("generated/apiConfig/commonMain/kotlin")
    inputs.property("apiKey", apiKey)
    outputs.dir(outputDir)
    doLast {
        val escapedKey = apiKey.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
        val file = outputDir.get().file("com/nb/app/core/network/ApiConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by the `generateApiConfig` Gradle task. Do not edit.
            |package com.nb.app.core.network
            |
            |internal object ApiConfig {
            |    const val BASE_URL: String = "https://api.balldontlie.io/v1/"
            |    const val API_KEY: String = "$escapedKey"
            |}
            |""".trimMargin(),
        )
    }
}

